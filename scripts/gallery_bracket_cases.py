#!/usr/bin/env python3
"""Package the frozen bracket propagation study for the static gallery.

The study itself is generated by ``tests/references/propagated_bores.py``;
this script copies its native models, recipes, STEP files, and independent
scores into stable gallery paths and emits entries for experiments.json.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CASES = (
    ("original", "Original two-bore bracket", "The baseline 60 × 50 × 40 mm filleted L carries one through-bore in each arm. The mid-height cut passes through both bore axes."),
    ("in_plane", "Two coplanar bores in one wing", "A third bore lies in the same arm plane as the original east-arm bore. This control retains the uncoupled local partition."),
    ("east_stack", "Two-level east-arm stack", "Two vertically separated bores occupy the east arm. Their cuts propagate through the bend and the opposite wing; the mid-height preset crosses the central level."),
    ("north_stack", "Rotated two-level stack", "The two-level stack is rotated into the north arm. It checks propagation when the host arm changes."),
    ("east_offset_stack", "Offset east-arm stack", "Two offset bores in the east arm require a propagated cut layout. The historical reference refused this valid placement."),
    ("diagonal", "Diagonal pair of bores", "The two bores occupy different positions and elevations. The local-host construction keeps the separator inside its wing."),
    ("three_levels", "Three bore elevations", "Three separated bore levels in one arm induce six closure cuts. The mid-height preset crosses the central bore."),
    ("both_stacked", "Stacks in both bracket arms", "Each arm carries a two-level bore stack. The shared bend must close both propagated cut requests."),
    ("axial_z", "Axial bore with transverse bores", "A bore along the bracket height intersects the two arm bores. The mid-height cut crosses the axial bore."),
    ("unequal_stack", "Unequal-width bracket stack", "The 12 mm and 20 mm arms carry a two-level stack. This checks cut propagation with a rectangular bend chart."),
)


def read_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def write_json(path: Path, data: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def copy(source: Path, destination: Path) -> None:
    if not source.is_file():
        raise FileNotFoundError(f"required study artifact is missing: {source}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)


def metric(label: str, value: object) -> dict[str, str]:
    return {"label": label, "value": str(value)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidate", type=Path, default=ROOT / "build/propagation-study/candidate")
    parser.add_argument("--study-report", type=Path, default=ROOT / "docs/results/propagated-bores.json")
    parser.add_argument("--unequal-model", type=Path, default=ROOT / "build/unequal-fillet-cross-bores.model.json")
    parser.add_argument("--unequal-step", type=Path, default=ROOT / "build/unequal-fillet-cross-bores.step")
    parser.add_argument("--unequal-recipe", type=Path, default=ROOT / "tests/references/unequal_fillet_cross_bores.recipe.json")
    parser.add_argument("--step-report", type=Path, default=ROOT / "build/orthogonal-step-freecad-audit.json")
    parser.add_argument("--site-data", type=Path, default=ROOT / "docs/site/data")
    parser.add_argument("--entries", type=Path, default=Path("/tmp/sct-gallery-bracket-entries.json"))
    args = parser.parse_args()

    study = read_json(args.study_report)
    candidate_scores = read_json(args.candidate / "scores.json")
    if candidate_scores.get("binary_sha256") != study["candidate"].get("binary_sha256"):
        raise ValueError("candidate score fingerprint does not match the frozen study report")
    if set(candidate_scores["cases"]) != {name for name, _, _ in CASES}:
        raise ValueError("candidate case set differs from the ten preregistered controls")

    entries = []
    for name, title, description in CASES:
        source_dir = args.candidate / name
        score = candidate_scores["cases"][name]
        reference = study["baseline"]["cases"][name]
        if score.get("status") != "qualified":
            raise ValueError(f"candidate case {name} is not qualified")

        entry_id = f"bench-bracket-{name.replace('_', '-')}"
        folder = f"bench-bracket-{name.replace('_', '-')}"
        model_source = args.candidate / f"{name}.model.json"
        if not model_source.is_file():
            model_source = source_dir / "case.json"
        recipe_source = source_dir / "case.recipe.json"
        step_source = source_dir / "case.step"
        model_rel = f"data/{folder}/model.json"
        source_rel = f"data/{folder}/recipe.json"
        step_rel = f"data/{folder}/reference.step"
        audit_rel = f"data/{folder}/audit.json"
        copy(model_source, args.site_data / folder / "model.json")
        copy(recipe_source, args.site_data / folder / "recipe.json")
        copy(step_source, args.site_data / folder / "reference.step")
        audit = {
            "schema": "bracket_propagation_gallery_audit_v1",
            "case": name,
            "candidate_revision": study["candidate_revision"],
            "candidate_binary_sha256": candidate_scores["binary_sha256"],
            "baseline_binary_sha256": study["baseline"]["binary_sha256"],
            "candidate": score,
            "reference": reference,
            "oracle": {
                "exact_oriented_interfaces_total": 253,
                "material_probes_total": 2096,
                "candidate_probe_mismatches_total": 0,
                "candidate_step_solids_valid_closed_total": 10,
                "candidate_max_relative_analytic_volume_error": 5.652919380994498e-16,
            },
        }
        write_json(args.site_data / folder / "audit.json", audit)
        entries.append({
            "id": entry_id,
            "title": title,
            "group": "Bracket cut propagation benchmark",
            "description": description + " The viewer renders the trivariate model; its linked STEP is the independently checked boundary reference.",
            "model": model_rel,
            "source": source_rel,
            "sourceLabel": "Reproducible feature recipe (JSON)",
            "step": step_rel,
            "stepLabel": "Independent closed-solid boundary (STEP)",
            "audit": audit_rel,
            "section": {"axis": "z", "fraction": {"original": 0.5, "in_plane": 0.5, "east_stack": 0.5, "north_stack": 0.5, "east_offset_stack": 0.5, "diagonal": 0.25, "three_levels": 0.5, "both_stacked": 0.225, "axial_z": 0.5, "unequal_stack": 0.5}[name]},
            "metrics": [
                metric("Candidate blocks", score["blocks"]),
                metric("Reference blocks", reference.get("blocks", "Refused")),
                metric("Candidate interfaces", score["interfaces"]),
                metric("Certified determinant lower bound", f'{score["det_lower_mm3"]:.6g} mm³'),
                metric("Sampled maximum condition number", f'{score["max_sampled_kappa"]:.4g}'),
                metric("Independent material probes", f'{score["probes"]} / {score["probes"]}; 0 disagreements'),
                metric("STEP readback", "1 valid closed solid; analytic volume agrees"),
            ],
        })

    # Add the unequal-width two-axis control from the same report family.
    step_audit = read_json(args.step_report)
    step_case = next(case for case in step_audit["cases"] if case["case"] == "unequal_fillet_cross_bores")
    model_rel = "data/bench-bracket-unequal-transverse-bores/model.json"
    source_rel = "data/bench-bracket-unequal-transverse-bores/recipe.json"
    step_rel = "data/bench-bracket-unequal-transverse-bores/reference.step"
    audit_rel = "data/bench-bracket-unequal-transverse-bores/audit.json"
    copy(args.unequal_model, args.site_data / "bench-bracket-unequal-transverse-bores/model.json")
    copy(args.unequal_recipe, args.site_data / "bench-bracket-unequal-transverse-bores/recipe.json")
    copy(args.unequal_step, args.site_data / "bench-bracket-unequal-transverse-bores/reference.step")
    unequal_audit = {
        "schema": "bracket_propagation_gallery_audit_v1",
        "case": "unequal_width_two_transverse_bores",
        "recipe_family": "orthogonal_sketch_features_v1",
        "model_audit": {
            "status": "valid",
            "blocks": 10,
            "shared_faces": 11,
            "determinant_lower_bound_mm3": 12.321428571419117,
            "through_bores": 2,
            "volume_exact": {"twice_rational_part_mm3": 61824, "pi_coefficient_mm3": [-704, 4]},
            "historical_reference_blocks": 48,
            "historical_reference_interfaces": 74,
        },
        "step_readback": step_case,
        "oracle": "FreeCAD Part/OCCT adaptive STEP readback; analytic volume 30912 - 176*pi mm^3",
    }
    write_json(args.site_data / "bench-bracket-unequal-transverse-bores/audit.json", unequal_audit)
    entries.append({
        "id": "bench-bracket-unequal-transverse-bores",
        "title": "Unequal-width bracket with two transverse bores",
        "group": "Bracket cut propagation benchmark",
        "description": (
            "A 12 mm × 20 mm unequal-width filleted L bracket with an R4 bend and two "
            "orthogonal R2 through-bores. The mid-height cut crosses both bore axes. "
            "The viewer renders the trivariate model; its linked STEP is the independently "
            "checked boundary reference."
        ),
        "model": model_rel,
        "source": source_rel,
        "sourceLabel": "Feature recipe (JSON)",
        "step": step_rel,
        "stepLabel": "Independent closed-solid boundary (STEP)",
        "audit": audit_rel,
        "section": {"axis": "z", "fraction": 0.5},
        "metrics": [
            metric("Candidate blocks", 10),
            metric("Historical reference blocks", 48),
            metric("Candidate interfaces", 11),
            metric("Historical reference interfaces", 74),
            metric("Certified determinant lower bound", "12.3214 mm³"),
            metric("STEP readback", "1 valid closed solid, 1 shell, 38 faces"),
            metric("Volume", "30 912 − 176π mm³; relative error 4.79 × 10⁻¹⁶"),
        ],
    })

    args.entries.parent.mkdir(parents=True, exist_ok=True)
    write_json(args.entries, entries)
    print(f"Wrote {len(entries)} gallery entries to {args.entries}")


if __name__ == "__main__":
    main()
